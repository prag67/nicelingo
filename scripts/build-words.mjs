// Generate src/lessons/word-timings.ts in the content repo: the real
// duration (seconds) of every phrase's default-voice clip, measured
// with ffprobe. The curriculum splits each duration across the
// phrase's words at build time (wordSlices in src/lessons/build.ts).
// Usage: node scripts/build-words.mjs [contentStaticDir]
// Re-runnable; phrases whose file is missing are reported, not fatal,
// but any missing file fails the run so gaps are fixed, not shipped.
import { execFile } from "node:child_process";
import { existsSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { promisify } from "node:util";

const run = promisify(execFile);
const staticDir = process.argv[2] ?? "/root/nicelingo-content/public/static";
const outPath =
  process.argv[3] ?? "/root/nicelingo-content/src/lessons/word-timings.ts";

const jobs = [];
for (const f of readdirSync("scripts/manifests").filter((x) => x.endsWith(".json"))) {
  const m = JSON.parse(readFileSync(join("scripts/manifests", f), "utf8"));
  for (const p of m.phrases) {
    jobs.push({ id: p.id, file: join(staticDir, p.audioUrl.replace(/^\/static\//, "")) });
  }
}
console.log(`${jobs.length} phrases`);

const durations = {};
let missing = 0;
async function worker() {
  for (;;) {
    const job = jobs.shift();
    if (!job) return;
    if (!existsSync(job.file)) {
      console.error(`MISSING ${job.id} ${job.file}`);
      missing++;
      continue;
    }
    const { stdout } = await run("ffprobe", [
      "-v", "error", "-show_entries", "format=duration", "-of", "csv=p=0", job.file,
    ]);
    durations[job.id] = Number(parseFloat(stdout.trim()).toFixed(3));
  }
}
await Promise.all(Array.from({ length: 24 }, () => worker()));
const ids = Object.keys(durations).sort();
const body = `// Generated by scripts/build-words.mjs: real clip durations
// (seconds) per phrase id, for tap-to-hear word timings. Do not edit.
export const WORD_DURATIONS: Record<string, number> = ${JSON.stringify(
  Object.fromEntries(ids.map((id) => [id, durations[id]])),
  null,
  1,
)};
`;
writeFileSync(outPath, body);
console.log(`wrote ${ids.length} durations to ${outPath}; missing=${missing}`);
if (missing) process.exit(1);
